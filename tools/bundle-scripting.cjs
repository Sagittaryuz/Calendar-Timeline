// Build coherent, self-contained host entries from Git-owned sources.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const ts=require('typescript'),{build:esbuild}=require('esbuild');
const root=path.resolve(__dirname,'../scripting/scripts/Calendar Timeline Scripting');
const sources=path.resolve(__dirname,'../scripting/entrypoints');
const entries=fs.readdirSync(sources).filter(n=>n.endsWith('.tsx'));
const version=JSON.parse(fs.readFileSync(path.join(root,'script.json'),'utf8')).version;
async function build(name){
 const result=await esbuild({stdin:{contents:fs.readFileSync(path.join(sources,name),'utf8'),sourcefile:name,resolveDir:root,loader:'tsx'},bundle:true,write:false,format:'esm',platform:'neutral',external:['scripting'],target:'es2020',jsx:'preserve',metafile:true,plugins:[{name:'canonical-entries',setup(b){b.onLoad({filter:/\.tsx$/},args=>{
  if(path.dirname(args.path)===root&&entries.includes(path.basename(args.path)))return {contents:fs.readFileSync(path.join(sources,path.basename(args.path)),'utf8'),loader:'tsx',resolveDir:root};
 })}}]});
 let code=result.outputFiles[0].text;
 const tree=ts.createSourceFile(name,code,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX),imports=[],bindings=[];
 for(const node of tree.statements)if(ts.isImportDeclaration(node)){
  if(node.moduleSpecifier.text!=='scripting')throw Error('Unbundled dependency: '+node.moduleSpecifier.text);
  const list=node.importClause?.namedBindings;
  if(!list||!ts.isNamedImports(list))throw Error('Unexpected native import');
  for(const item of list.elements)bindings.push(`const ${item.name.text} = __calendarNativeHost[${JSON.stringify((item.propertyName??item.name).text)}];`);
  imports.push([node.getStart(tree),node.end]);
 }
 for(const [a,b] of imports.reverse())code=code.slice(0,a)+code.slice(b);
 const main=name==='index.tsx'||name==='widget.tsx';
 if(main){
  if(tree.statements.some(ts.isExportDeclaration))throw Error('Main entry unexpectedly exports symbols');
  const fallback=name==='widget.tsx'
   ? `const ErrorText=__calendarNativeHost.Text; __calendarNativeHost.Widget.present(<ErrorText widgetBackground="#0A0A0B" foregroundStyle="white">{message}</ErrorText>,{policy:'after',date:new Date(Date.now()+60000)});`
   : `if(typeof Dialog!=='undefined')Promise.resolve(Dialog.alert({title:'Calendar Timeline '+${JSON.stringify(version)},message})).finally(()=>__calendarNativeHost.Script.exit()); else console.error(message);`;
  code=code.replace(/\nmain\(\);\n/, '\nPromise.resolve(main()).catch(__calendarBootFailure);\n');
  code=`function __calendarBootFailure(error) {\nconst message='Calendar Timeline '+${JSON.stringify(version)}+': '+String(error instanceof Error?error.message:error);\n${fallback}\n}\ntry {\n${code}\n} catch(error) { __calendarBootFailure(error); }\n`;
 }
 return `// GENERATED by tools/bundle-scripting.cjs. Edit scripting/entrypoints/${name}.\n// Calendar Timeline ${version}; all project dependencies are embedded.\nimport * as __calendarNativeHost from 'scripting';\n${bindings.join('\n')}\n${code}`;
}
(async()=>{
const files=[];
for(const name of entries){const code=await build(name);fs.writeFileSync(path.join(root,name),code);files.push({name,bytes:Buffer.byteLength(code),sha256:crypto.createHash('sha256').update(code).digest('hex')});}
const sourceFiles=fs.readdirSync(root).filter(name=>/\.(tsx?|js|json)$/.test(name)&&!['build-manifest.json','diagnose.tsx'].includes(name)).map(name=>{
 const content=fs.readFileSync(path.join(root,name),'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
 return {name,sha256:crypto.createHash('sha256').update(content).digest('hex')};
});
const diagnostic=fs.readFileSync(path.join(__dirname,'diagnose-template.tsx.txt'),'utf8').replace('__VERSION__',JSON.stringify(version)).replace('__FILES__',JSON.stringify(sourceFiles));
fs.writeFileSync(path.join(root,'diagnose.tsx'),diagnostic);
fs.writeFileSync(path.join(root,'build-manifest.json'),JSON.stringify({version,format:'self-contained-esm-tsx',files,sourceFiles},null,2)+'\n');
console.log(JSON.stringify({version,entries:files.map(({name,bytes})=>({name,bytes}))}));

})().catch(e=>{console.error(e);process.exitCode=1});
